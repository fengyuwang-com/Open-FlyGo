// tray.rs - system tray icon + popup menu (handwritten Win32 via the windows
// crate, running on its own std::thread with a message loop).
//
// The menu is rebuilt right before every popup so the status area is fresh.
// Menu commands are forwarded over a std mpsc channel to the main thread,
// which executes them against the shared DaemonState. The tray thread itself
// only builds menus and reads status.
//
// All code comments are pure ASCII; menu labels may be UTF-8.

use std::sync::{mpsc, Arc, OnceLock};

use windows::core::{w, PCWSTR};
use windows::Win32::Foundation::{HWND, LPARAM, LRESULT, POINT, WPARAM};
use windows::Win32::System::LibraryLoader::GetModuleHandleW;
use windows::Win32::UI::Shell::{
    NIF_INFO, NIF_ICON, NIF_MESSAGE, NIF_TIP, NIIF_NONE, NIM_ADD, NIM_DELETE, NIM_MODIFY,
    NOTIFYICONDATAW, ShellExecuteW, Shell_NotifyIconW,
};
use windows::Win32::UI::WindowsAndMessaging::{
    AppendMenuW, CreatePopupMenu, CreateWindowExW, DefWindowProcW, DestroyMenu, DispatchMessageW,
    GetCursorPos, GetMessageW, HICON, HMENU, HWND_MESSAGE, IMAGE_ICON, LoadImageW, LR_LOADFROMFILE,
    MENU_ITEM_FLAGS, MF_GRAYED, MF_SEPARATOR, MF_STRING, MSG, PostMessageW, PostQuitMessage,
    RegisterClassW, SetForegroundWindow, SW_HIDE, TPM_RETURNCMD, TPM_RIGHTBUTTON,
    TrackPopupMenu, TranslateMessage, WINDOW_EX_STYLE, WINDOW_STYLE, WNDCLASSW, WM_APP,
    WM_COMMAND, WM_DESTROY, WM_ENDSESSION, WM_LBUTTONUP, WM_NULL, WM_QUERYENDSESSION,
    WM_RBUTTONUP, WS_EX_TOOLWINDOW,
};

use crate::daemon::DaemonState;
use crate::log::{log_error, log_warn};

/// Custom icon callback message (WM_APP + 1).
const TRAY_CALLBACK_MSG: u32 = WM_APP + 1;
/// Main thread -> tray: remove icon and quit (WM_APP + 2).
const TRAY_EXIT_MSG: u32 = WM_APP + 2;
/// Tray icon identifier.
const TRAY_ICON_ID: u32 = 1;

// Menu item ids (status area first, then actions).
const IDM_STATUS_WEB: usize = 1;
const IDM_STATUS_DOCKER: usize = 2;
const IDM_STATUS_USB: usize = 3;
const IDM_STATUS_TIMER: usize = 4;
const IDM_TOGGLE_DOCKER: usize = 10;
const IDM_RESTART_WEB: usize = 11;
const IDM_EJECT_USB: usize = 12;
const IDM_OPEN_PANEL: usize = 20;
const IDM_EXIT: usize = 21;

/// Commands the tray menu sends to the main thread.
pub enum TrayCmd {
    ToggleDocker,
    RestartWebcli,
    EjectUsb,
    OpenPanel,
    Exit,
}

/// Embedded tray icon (generated by PowerShell System.Drawing at build time).
const TRAY_ICO: &[u8] = include_bytes!("../static/tray.ico");

// Shared from the tray thread to the wnd proc (same process, single instance).
static DAEMON: OnceLock<Arc<DaemonState>> = OnceLock::new();
static CMD_TX: OnceLock<mpsc::Sender<TrayCmd>> = OnceLock::new();
static TRAY_HWND: OnceLock<HWND> = OnceLock::new();

/// Start the tray thread. Call once at startup.
pub fn spawn(state: Arc<DaemonState>, tx: mpsc::Sender<TrayCmd>) {
    let _ = DAEMON.set(state);
    let _ = CMD_TX.set(tx);
    std::thread::Builder::new()
        .name("tray".into())
        .spawn(move || unsafe {
            tray_main();
        })
        .ok();
}

/// Ask the tray thread to remove its icon and quit (called during shutdown).
pub fn request_tray_cleanup() {
    if let Some(hwnd) = TRAY_HWND.get() {
        unsafe {
            let _ = PostMessageW(*hwnd, TRAY_EXIT_MSG, WPARAM(0), LPARAM(0));
        }
    }
}

/// Launch the portproxy script elevated (UAC prompt). The UAC dialog is
/// expected; -WindowStyle Hidden keeps the elevated PowerShell console out of
/// sight once approved. Script path is user-configurable (FENGPAGE_PORTPROXY_SCRIPT);
/// when not installed the menu item is simply a no-op with a log line.
/// SW_HIDE (not SHOWNORMAL): SHOWNORMAL flashes a visible console despite
/// -WindowStyle Hidden (show-cmd race); the UAC consent prompt is unaffected.
pub fn run_port_proxy() {
    let Some(script) = crate::config::get().portproxy_script.clone() else {
        eprintln!("[tray] portproxy script not configured; set FENGPAGE_PORTPROXY_SCRIPT");
        return;
    };
    let ps = script.to_string_lossy();
    let file = wstr("powershell.exe");
    let args = wstr(&format!(
        "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File \"{ps}\""
    ));
    unsafe {
        ShellExecuteW(
            None,
            w!("runas"),
            PCWSTR(file.as_ptr()),
            PCWSTR(args.as_ptr()),
            PCWSTR::null(),
            SW_HIDE,
        );
    }
}

/// Safe-eject the external USB drives. The caller stops the drive-dependent
/// components first; this launches one elevated PowerShell that runs
/// `mountvol <letter>: /p` for every drive (a single UAC prompt).
/// -WindowStyle Hidden keeps the elevated console out of sight once approved.
/// SW_HIDE: see run_port_proxy (same show-cmd race).
pub fn eject_usb_drives(letters: &[String]) {
    if letters.is_empty() {
        return;
    }
    let cmds: Vec<String> = letters.iter().map(|l| format!("mountvol {l}: /p")).collect();
    let joined = cmds.join("; ");
    let file = wstr("powershell.exe");
    let args = wstr(&format!(
        "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -Command \"{joined}\""
    ));
    unsafe {
        ShellExecuteW(
            None,
            w!("runas"),
            PCWSTR(file.as_ptr()),
            PCWSTR(args.as_ptr()),
            PCWSTR::null(),
            SW_HIDE,
        );
    }
}

/// Show a tray balloon notification (best-effort, fire-and-forget).
pub fn notify(title: &str, msg: &str) {
    unsafe {
        let Some(hwnd) = TRAY_HWND.get() else {
            return;
        };
        let mut nid = NOTIFYICONDATAW {
            cbSize: std::mem::size_of::<NOTIFYICONDATAW>() as u32,
            hWnd: *hwnd,
            uID: TRAY_ICON_ID,
            uFlags: NIF_INFO,
            dwInfoFlags: NIIF_NONE,
            ..Default::default()
        };
        copy_wide(&mut nid.szInfoTitle, title);
        copy_wide(&mut nid.szInfo, msg);
        nid.Anonymous.uTimeout = 6000;
        Shell_NotifyIconW(NIM_MODIFY, &nid);
    }
}

// ---------- message loop ----------

unsafe fn tray_main() {
    let hinst: windows::Win32::Foundation::HINSTANCE =
        GetModuleHandleW(None).unwrap_or_default().into();
    let wc = WNDCLASSW {
        lpfnWndProc: Some(wnd_proc),
        hInstance: hinst,
        lpszClassName: w!("FlyGoTrayWnd"),
        ..Default::default()
    };
    if RegisterClassW(&wc) == 0 {
        log_error!("tray.setup", "RegisterClassW failed");
        eprintln!("[tray] RegisterClassW failed");
        return;
    }

    // Hidden top-level window (parent = None, NOT HWND_MESSAGE). Win32 never
    // broadcasts session messages (WM_QUERYENDSESSION / WM_ENDSESSION) to
    // message-only windows, so a message-only window would silently miss the
    // shutdown/logoff path. As an ordinary top-level window it receives the
    // broadcast. Style has no WS_VISIBLE and we never ShowWindow, so it stays
    // invisible; WS_EX_TOOLWINDOW keeps it off the taskbar / Alt-Tab.
    let hwnd = CreateWindowExW(
        WS_EX_TOOLWINDOW,
        w!("FlyGoTrayWnd"),
        w!("FlyGoTray"),
        WINDOW_STYLE(0),
        0,
        0,
        0,
        0,
        HWND(0),
        HMENU(0),
        hinst,
        None,
    );
    if hwnd.0 == 0 {
        log_error!("tray.setup", "CreateWindowExW failed");
        eprintln!("[tray] CreateWindowExW failed");
        return;
    }
    let _ = TRAY_HWND.set(hwnd);

    let hicon = load_icon(hinst);
    let nid = build_nid(hwnd, hicon);
    if !Shell_NotifyIconW(NIM_ADD, &nid).as_bool() {
        log_error!("tray.setup", "Shell_NotifyIconW NIM_ADD failed");
        eprintln!("[tray] Shell_NotifyIconW NIM_ADD failed");
    }

    let mut msg = MSG::default();
    loop {
        let ret = GetMessageW(&mut msg, HWND(0), 0, 0);
        if ret.0 == 0 || ret.0 == -1 {
            break; // WM_QUIT or error
        }
        TranslateMessage(&msg);
        DispatchMessageW(&msg);
    }

    // Loop only ends on a quit request: remove the icon and let this worker
    // thread end naturally by returning. Never call std::process::exit() here:
    // the process lifetime is owned by the main thread, which runs the full
    // graceful shutdown (smb::close_app() and friends) before returning. A
    // hard exit() from this thread would tear the whole process down
    // mid-shutdown, racing the main thread's cleanup and leaving resources
    // (e.g. SMB shares) behind. Icons are already removed in the TRAY_EXIT_MSG
    // / WM_DESTROY handlers; the call below is a harmless second NIM_DELETE.
    remove_icon(hwnd);
}

unsafe fn build_nid(hwnd: HWND, hicon: HICON) -> NOTIFYICONDATAW {
    let mut sz_tip = [0u16; 128];
    let tip: Vec<u16> = "FlyGo 面板管家".encode_utf16().collect();
    let n = tip.len().min(127);
    sz_tip[..n].copy_from_slice(&tip[..n]);
    NOTIFYICONDATAW {
        cbSize: std::mem::size_of::<NOTIFYICONDATAW>() as u32,
        hWnd: hwnd,
        uID: TRAY_ICON_ID,
        uFlags: NIF_MESSAGE | NIF_ICON | NIF_TIP,
        uCallbackMessage: TRAY_CALLBACK_MSG,
        hIcon: hicon,
        szTip: sz_tip,
        ..Default::default()
    }
}

unsafe fn remove_icon(hwnd: HWND) {
    let mut nid = NOTIFYICONDATAW::default();
    nid.cbSize = std::mem::size_of::<NOTIFYICONDATAW>() as u32;
    nid.hWnd = hwnd;
    nid.uID = TRAY_ICON_ID;
    Shell_NotifyIconW(NIM_DELETE, &nid);
}

/// Write the embedded ICO to a temp file and load it as HICON.
unsafe fn load_icon(hinst: windows::Win32::Foundation::HINSTANCE) -> HICON {
    let path = std::env::temp_dir().join("flygo-tray.ico");
    if std::fs::write(&path, TRAY_ICO).is_err() {
        eprintln!("[tray] failed to write temp icon file");
        return HICON(0);
    }
    let wide = wstr(&path.to_string_lossy());
    match LoadImageW(hinst, PCWSTR(wide.as_ptr()), IMAGE_ICON, 32, 32, LR_LOADFROMFILE) {
        Ok(handle) if !handle.is_invalid() => HICON(handle.0),
        Ok(_) => {
            eprintln!("[tray] LoadImageW returned null handle");
            HICON(0)
        }
        Err(e) => {
            eprintln!("[tray] LoadImageW failed: {e}");
            HICON(0)
        }
    }
}

// ---------- window procedure ----------

#[allow(unsafe_op_in_unsafe_fn)]
unsafe extern "system" fn wnd_proc(hwnd: HWND, msg: u32, wparam: WPARAM, lparam: LPARAM) -> LRESULT {
    match msg {
        TRAY_CALLBACK_MSG => {
            let ev = lparam.0 as u32;
            if ev == WM_LBUTTONUP || ev == WM_RBUTTONUP {
                show_menu(hwnd);
            }
            LRESULT(0)
        }
        TRAY_EXIT_MSG => {
            remove_icon(hwnd);
            PostQuitMessage(0);
            LRESULT(0)
        }
        WM_DESTROY => {
            PostQuitMessage(0);
            LRESULT(0)
        }
        WM_COMMAND => {
            // Not used (TrackPopupMenu runs with TPM_RETURNCMD), kept for safety.
            LRESULT(0)
        }
        WM_QUERYENDSESSION => {
            // Shutdown/logoff: agree to end the session. Cleanup happens on
            // WM_ENDSESSION, not here (per Win32 convention).
            LRESULT(1)
        }
        WM_ENDSESSION => {
            // Windows is shutting down / logging off. This is the ONLY hook we
            // get in that path (the process is torn down without any other
            // chance to clean up). Run the SMB share removal synchronously
            // while the grace period still allows it; direct call (no thread
            // wrapper) because close_app is itself bounded (~2s typical, 8s
            // hard cap) and this keeps the code path simple and panic-visible.
            crate::log::log(
                "INFO",
                "tray.session",
                "session ending; removing SMB shares before process teardown",
            );
            crate::smb::close_app();
            crate::log::log("INFO", "tray.session", "session-end SMB cleanup done");
            LRESULT(0)
        }
        _ => DefWindowProcW(hwnd, msg, wparam, lparam),
    }
}

// ---------- popup menu ----------

#[allow(unsafe_op_in_unsafe_fn)]
unsafe fn show_menu(hwnd: HWND) {
    let Some(daemon) = DAEMON.get().cloned() else {
        return;
    };
    daemon.refresh();
    let sync_on = daemon.sync_enabled();
    let ext_present = daemon.external_present();
    let docker_on = crate::api::dockerctl::wsl_vm_running();

    let web = daemon.status("webcli");

    let m = match CreatePopupMenu() {
        Ok(m) => m,
        Err(e) => {
            log_error!("tray.menu", "CreatePopupMenu failed: {e}");
            eprintln!("[tray] CreatePopupMenu failed: {e}");
            return;
        }
    };
    append(m, MF_GRAYED, IDM_STATUS_WEB, &status_label("webcli", &web));
    append(
        m,
        MF_GRAYED,
        IDM_STATUS_DOCKER,
        &if docker_on {
            "Docker 引擎 · 运行中".to_string()
        } else {
            "Docker 引擎 · 已停机".to_string()
        },
    );
    append(
        m,
        MF_GRAYED,
        IDM_STATUS_USB,
        &if ext_present {
            "外置盘 · 在线".to_string()
        } else {
            "外置盘 · 已弹出".to_string()
        },
    );
    append(
        m,
        MF_GRAYED,
        IDM_STATUS_TIMER,
        &if sync_on {
            "同步定时器 · 已开启".to_string()
        } else {
            "同步定时器 · 已关闭".to_string()
        },
    );
    separator(m);

    append(
        m,
        MF_STRING,
        IDM_TOGGLE_DOCKER,
        &if docker_on {
            "关闭 Docker 引擎（停止全部容器）".to_string()
        } else {
            "开启 Docker 引擎".to_string()
        },
    );
    append(
        m,
        MF_STRING,
        IDM_RESTART_WEB,
        &if web.running {
            "重启 webcli".to_string()
        } else {
            "启动 webcli".to_string()
        },
    );
    append(
        m,
        if ext_present { MF_STRING } else { MF_GRAYED },
        IDM_EJECT_USB,
        "安全弹出外置盘（停依赖→卸载）",
    );
    separator(m);

    append(m, MF_STRING, IDM_OPEN_PANEL, "打开面板");
    separator(m);
    append(m, MF_STRING, IDM_EXIT, "退出(停止全部后台)");

    SetForegroundWindow(hwnd);
    let mut pt = POINT::default();
    let _ = GetCursorPos(&mut pt);
    let ret = TrackPopupMenu(m, TPM_RIGHTBUTTON | TPM_RETURNCMD, pt.x, pt.y, 0, hwnd, None);
    let _ = PostMessageW(hwnd, WM_NULL, WPARAM(0), LPARAM(0));
    let _ = DestroyMenu(m);

    let id = ret.0 as usize;
    dispatch(id);
}

fn status_label(name: &str, st: &crate::daemon::ChildStatus) -> String {
    if st.running && st.pid > 0 {
        format!("{name} · 运行中 (PID {})", st.pid)
    } else {
        format!("{name} · 已停止")
    }
}

/// Forward the selected menu item to the main thread over the channel.
fn dispatch(id: usize) {
    let Some(tx) = CMD_TX.get() else {
        return;
    };
    let (cmd, label) = if id == IDM_TOGGLE_DOCKER {
        (TrayCmd::ToggleDocker, "toggle-docker")
    } else if id == IDM_RESTART_WEB {
        (TrayCmd::RestartWebcli, "restart-webcli")
    } else if id == IDM_EJECT_USB {
        (TrayCmd::EjectUsb, "eject-usb")
    } else if id == IDM_OPEN_PANEL {
        (TrayCmd::OpenPanel, "open-panel")
    } else if id == IDM_EXIT {
        (TrayCmd::Exit, "exit")
    } else {
        return;
    };
    crate::log::log("INFO", "tray.menu", &format!("menu item {label} (id {id}) sent"));
    let _ = tx.send(cmd);
}

unsafe fn append(m: HMENU, flags: MENU_ITEM_FLAGS, id: usize, text: &str) {
    let wide = wstr(text);
    let _ = AppendMenuW(m, flags, id, PCWSTR(wide.as_ptr()));
}

unsafe fn separator(m: HMENU) {
    let _ = AppendMenuW(m, MF_SEPARATOR, 0, PCWSTR::null());
}

// ---------- helpers ----------

/// UTF-16 wide string with a trailing NUL (for PCWSTR params).
fn wstr(s: &str) -> Vec<u16> {
    s.encode_utf16().chain(std::iter::once(0)).collect()
}

/// Copy a UTF-8 string into a fixed-size UTF-16 buffer, NUL-padding the rest.
fn copy_wide(dst: &mut [u16], s: &str) {
    let mut it = s.encode_utf16();
    for slot in dst.iter_mut() {
        *slot = match it.next() {
            Some(u) => u,
            None => 0,
        };
    }
}
